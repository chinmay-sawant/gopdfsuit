// Build-time manifest check (Phase 3.4): PDFA_FONT_MANIFEST must match
// internal/pdf/font/pdfa.go (LiberationFontMapping + LiberationFontFiles)
// and BUNDLED_TEMPLATES must match public/templates/*.json. Run without
// flags to check (exits 1 on drift, failing `npm run build` via prebuild);
// run with --write to regenerate src/utils/wasm/manifests.generated.js.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const frontendDir = join(here, '..')
const repoDir = join(frontendDir, '..')
const generatedPath = join(frontendDir, 'src', 'utils', 'wasm', 'manifests.generated.js')

const pdfaGo = readFileSync(join(repoDir, 'internal', 'pdf', 'font', 'pdfa.go'), 'utf8')

function parseMapBlock(source, varName) {
  const block = source.match(new RegExp(`var ${varName} = map\\[string\\]string\\{([\\s\\S]*?)\\n\\}`))
  if (!block) throw new Error(`could not find ${varName} in pdfa.go`)
  const entries = []
  for (const match of block[1].matchAll(/"([^"]+)":\s*"([^"]+)"/g)) {
    entries.push([match[1], match[2]])
  }
  return entries
}

const mapping = parseMapBlock(pdfaGo, 'LiberationFontMapping')
const files = new Map(parseMapBlock(pdfaGo, 'LiberationFontFiles'))

const manifest = mapping.map(([std, lib]) => {
  const file = files.get(lib)
  if (!file) throw new Error(`no LiberationFontFiles entry for ${lib} (mapped from ${std})`)
  return { name: std, file }
})

const templates = readdirSync(join(frontendDir, 'public', 'templates'))
  .filter((name) => name.endsWith('.json'))
  .sort()

const generated = `// GENERATED by scripts/check-wasm-manifests.mjs from
// internal/pdf/font/pdfa.go (LiberationFontMapping + LiberationFontFiles)
// and public/templates/. Do not hand-edit: the prebuild check fails the
// build on drift (run with --write to regenerate).
export const PDFA_FONT_MANIFEST = ${JSON.stringify(manifest, null, 2)}

export const BUNDLED_TEMPLATES = ${JSON.stringify(templates, null, 2)}
`

const current = existsSync(generatedPath) ? readFileSync(generatedPath, 'utf8') : null
if (current === generated) {
  console.log(`manifests in sync (${manifest.length} fonts, ${templates.length} templates)`)
  process.exit(0)
}
if (process.argv.includes('--write')) {
  writeFileSync(generatedPath, generated)
  console.log(`wrote ${generatedPath} (${manifest.length} fonts, ${templates.length} templates)`)
  process.exit(0)
}
console.error('WASM manifest drift detected:')
console.error(`- regenerate with: node scripts/check-wasm-manifests.mjs --write`)
console.error(`- then inspect the diff of ${generatedPath}`)
process.exit(1)
